export const Sidebar = ({ isOpen, onClose }) => {
  const { user } = useAuth();

  const navigationItems = [
    { label: 'Dashboard', path: '/', Icon: NavIcons.Dashboard },
    { label: 'Donors', path: '/donors', Icon: NavIcons.Donors },
    { label: 'Donations', path: '/donations', Icon: NavIcons.Donations },
    { label: 'Blood Stock', path: '/stock', Icon: NavIcons.BloodStock },
    { label: 'Blood Requests', path: '/requests', Icon: NavIcons.BloodRequests },
    { label: 'Profile', path: '/profile', Icon: NavIcons.Profile },
  ];

  if (user?.role === 'admin' || user?.role === 'staff') {
    navigationItems.push({ label: 'Reports', path: '/reports', Icon: NavIcons.Reports });
    navigationItems.push({ label: 'Data Import', path: '/imports', Icon: NavIcons.DataImport });
  }

  if (user?.role === 'admin') {
    navigationItems.push({ label: 'Users', path: '/users', Icon: NavIcons.Users });
    navigationItems.push({ label: 'Audit Logs', path: '/audit-logs', Icon: NavIcons.AuditLogs });
    navigationItems.push({ label: 'Settings', path: '/settings', Icon: NavIcons.Settings });
    navigationItems.push({ label: 'Backups', path: '/backups', Icon: NavIcons.Backups });
    navigationItems.push({ label: 'System Health', path: '/health', Icon: NavIcons.Health });
  }

  const userInitial = user?.full_name ? user.full_name[0].toUpperCase() : 'U';

  return (
    <aside className={`sidebar ${isOpen ? 'open' : ''}`} data-testid="sidebar">
      <div className="sidebar-header">
        <NavLink to="/" className="sidebar-brand" onClick={onClose}>
          <div className="brand-logo-container">
            <svg viewBox="0 0 24 24" fill="currentColor" width="22" height="22" aria-hidden="true" className="brand-drop-svg">
              <path d="M12 2.69l5.66 5.66a8 8 0 1 1-11.31 0z" />
            </svg>
          </div>
          <div className="brand-text-wrapper">
            <span className="brand-title">Blood Care</span>
            <span className="brand-subtitle">Clinical Management</span>
          </div>
        </NavLink>
        <button
          className="sidebar-close-btn"
          onClick={onClose}
          aria-label="Close sidebar"
        >
          <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" width="18" height="18">
            <line x1="18" y1="6" x2="6" y2="18" />
            <line x1="6" y1="6" x2="18" y2="18" />
          </svg>
        </button>
      </div>

      <nav className="sidebar-nav">
        <div className="nav-section-label">MAIN NAVIGATION</div>
        {navigationItems.map(({ label, path, Icon }) => (
          <NavLink
            key={path}
            to={path}
            end={path === '/'}
            className={({ isActive }) => `nav-item ${isActive ? 'active' : ''}`}
            onClick={onClose}
          >
            <span className="nav-icon"><Icon /></span>
            <span className="nav-label">{label}</span>
          </NavLink>
        ))}
      </nav>

      <div className="sidebar-footer">
        <div className="user-profile-widget">
          <div className="user-avatar-circle">{userInitial}</div>
          <div className="user-meta">
            <span className="user-meta-name" data-testid="sidebar-user-name">
              {user?.full_name || 'User'}
            </span>
            <span className="user-meta-role" data-testid="sidebar-user-role">
              {user?.role || 'Guest'}
            </span>
          </div>
        </div>
      </div>
    </aside>
  );
};

export default Sidebar;
